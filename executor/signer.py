"""
executor/signer.py
==================
THE single authoritative transaction-signing path (DSS-WO-ENG-015 R4).

Signing responsibility lives here — restored to the existing architecture
and hardened with the wallet-custody improvements from R0–R3. There is NO
second signer and NO fallback signing implementation anywhere in the
repository.

Enforcement at this boundary (every step fails closed):

  1. the master execution switch (EXECUTE_ONCHAIN) must be enabled — read
     from the REAL process environment at call time via
     ``config.execution_enabled()``; a disabled run cannot sign;
  2. the RPC-REPORTED chain ID must equal the executor's expected chain —
     verified BEFORE signing and re-verified IMMEDIATELY before the sign
     call (an RPC failover that silently switches networks between the two
     reads is refused);
  3. the unsigned transaction's ``chainId`` must match the expected chain;
  4. the wallet is decrypted ONLY through ``load_wallet()`` — the single
     authoritative custody path below — and the derived address is bound
     to the recorded public agent identity (a mismatch refuses to return
     the account at all).

Wallet custody and provisioning arrangement (DSS-WO-ENG-015 R4)
--------------------------------------------------------------
The engine NEVER creates, funds or auto-generates a wallet. The DSS
runtime provisions an out-of-band secret store — a directory OUTSIDE the
repository containing

  * ``dss_wallet.keystore.json``  web3 secret-storage v3 keystore (0600)
  * ``dss_wallet.pass``           hex-encoded passphrase file  (0600)
  * ``dss_wallet.address``        recorded public identity    (0600-ish)

and exports its location as ``DSS_SECRET_STORE``. In the current DSS agent
deployment that directory is the runtime secret store previously populated
by ``scripts/dss_wallet_generate.py`` (files there still carry the retired
``dss_testnet_wallet.*`` names — a rename to the names above is a one-line
operator provisioning step, reported separately; nothing is renamed or
regenerated by the engine). The path is NEVER hardcoded into the code and
NEVER resolved to a repository-relative location: with ``DSS_SECRET_STORE``
unset the signer fails closed.

Secret-file checks (presence, regular file, no symlinks, 0600 on
keystore/passphrase, 0700 on their directory) run before every load —
including at signing time, so a permission regression between calls is
caught. Secret material is never printed, logged or serialized; signing
exceptions are reduced to their exception class name so key material can
never escape through an error message.
"""
from __future__ import annotations

import json
import os
import stat

from config import execution_enabled
from .errors import ExecutionRefused
from .audit import sanitize_error

from log import get_logger

log = get_logger("executor.signer")

# ── The DSS secret store (provisioning arrangement) ──────────────────────────

# The environment variable the DSS runtime sets to the agent secret-store
# directory. Fail-closed when unset — there is no default path.
SECRET_STORE_ENV = "DSS_SECRET_STORE"

KEYSTORE_FILENAME = "dss_wallet.keystore.json"
PASSPHRASE_FILENAME = "dss_wallet.pass"
ADDRESS_FILENAME = "dss_wallet.address"

# Secret files must expose no group/world bits; their directory must not be
# accessible to other users. The recorded address file is public metadata and
# is only checked for presence/type.
SECRET_MODE_MASK = 0o077


def secret_store_dir() -> str:
    """Resolve the DSS secret-store directory from the REAL process
    environment. Fail closed when unset — the engine has no default
    secret location and never resolves one inside the repository."""
    store = os.environ.get(SECRET_STORE_ENV, "").strip()
    if not store:
        raise ExecutionRefused(
            f"{SECRET_STORE_ENV} is not set — the DSS runtime must provision "
            "the agent secret store outside the repository and export its "
            "directory; refusing to touch wallet custody"
        )
    return store


def keystore_path() -> str:
    return os.path.join(secret_store_dir(), KEYSTORE_FILENAME)


def passphrase_path() -> str:
    return os.path.join(secret_store_dir(), PASSPHRASE_FILENAME)


def address_path() -> str:
    return os.path.join(secret_store_dir(), ADDRESS_FILENAME)


# ── Secret-store custody checks ──────────────────────────────────────────────

def _check_restricted_file(path: str, label: str) -> None:
    """Presence + file type + restrictive permissions, fail closed."""
    if os.path.islink(path):
        raise ExecutionRefused(
            f"agent {label} must be a regular file, not a symlink: {path}"
        )
    if not os.path.isfile(path):
        raise ExecutionRefused(f"agent {label} missing or not a regular file: {path}")
    mode = stat.S_IMODE(os.stat(path).st_mode)
    if mode & SECRET_MODE_MASK:
        raise ExecutionRefused(
            f"agent {label} permissions too open ({oct(mode)}): group/world "
            "access must be removed (0600 expected)"
        )


def _check_secret_dir(path: str, label: str) -> None:
    if os.path.islink(path):
        raise ExecutionRefused(
            f"agent {label} directory must not be a symlink: {path}"
        )
    if not os.path.isdir(path):
        raise ExecutionRefused(f"agent {label} directory missing: {path}")
    mode = stat.S_IMODE(os.stat(path).st_mode)
    if mode & SECRET_MODE_MASK:
        raise ExecutionRefused(
            f"agent {label} directory accessible to other users ({oct(mode)}): "
            "0700 expected"
        )


def verify_secret_store() -> None:
    """Verify presence, type and permissions of every secret-store file
    before any wallet operation.

    Fail closed on: missing files, non-regular files, symlinks, group/world
    access on keystore/passphrase, group/world access on their directory,
    or a malformed recorded address. Never reads secret contents.
    """
    for label, path in (
        ("keystore", keystore_path()),
        ("passphrase", passphrase_path()),
    ):
        _check_restricted_file(path, label)
        _check_secret_dir(os.path.dirname(path) or ".", label)
    addr = address_path()
    if os.path.islink(addr) or not os.path.isfile(addr):
        raise ExecutionRefused(
            f"agent recorded-address file missing, a symlink or not a regular "
            f"file: {addr}"
        )
    recorded_agent_address()


def recorded_agent_address() -> str:
    """Read the (non-secret) recorded agent identity — PUBLIC metadata.

    No key material is involved: this is the address the executor builds
    transactions with and the identity every signing/submission boundary
    binds against. Fail closed when malformed or absent.
    """
    with open(address_path()) as f:
        addr = f.read().strip()
    if (
        not addr.startswith("0x")
        or len(addr) != 42
        or any(c not in "0123456789abcdefABCDEF" for c in addr[2:])
    ):
        raise ExecutionRefused("recorded agent address is malformed")
    return addr


def get_sender() -> str:
    """Return the EOA address of the recorded agent identity (public)."""
    return recorded_agent_address()


def decode_passphrase_file(path: str) -> bytes:
    """Decode the keystore passphrase file — THE central keystore format.

    The DSS secret store stores the ASCII hex encoding of the passphrase
    bytes (machine-generated at wallet creation; see
    scripts/dss_wallet_generate.py). This is the only supported decoding;
    there is no environment override and no raw-text fallback.
    """
    with open(path, "rb") as f:
        raw = f.read().strip()
    try:
        return bytes.fromhex(raw.decode("ascii"))
    except (ValueError, UnicodeDecodeError) as exc:
        raise ExecutionRefused(
            "agent keystore passphrase file is not valid hex-encoded "
            "passphrase data (central keystore format)"
        ) from exc


def load_wallet():
    """THE single wallet-loading path for every signing operation.

    Sequence (fail closed):
      1. verify_secret_store (presence, types, symlinks, permissions);
      2. load the web3 secret-storage v3 keystore JSON (shape-validated);
      3. decode the hex-encoded passphrase file (central keystore format);
      4. decrypt via eth_account and build a proper LocalAccount with
         Account.from_key (the supported eth-account interface);
      5. BIND the derived address to the recorded public address file —
         a mismatch refuses to return the account at all.

    Returns the in-memory LocalAccount only. The key bytes and passphrase
    are dropped before returning and are never printed, logged or
    serialized. Decryption failures are reduced to their exception class
    name so no secret-derived diagnostic can escape.
    """
    from eth_account import Account

    verify_secret_store()

    with open(keystore_path()) as f:
        keystore = json.load(f)
    if (
        not isinstance(keystore, dict)
        or int(keystore.get("version", 0)) != 3
        or not isinstance(keystore.get("crypto"), dict)
    ):
        raise ExecutionRefused(
            "agent keystore is not a web3 secret-storage v3 JSON keystore"
        )

    passphrase = decode_passphrase_file(passphrase_path())
    try:
        key_bytes = Account.decrypt(keystore, passphrase)
    except Exception as exc:
        raise ExecutionRefused(
            f"agent wallet custody failed during decryption "
            f"({type(exc).__name__})"
        ) from None
    try:
        account = Account.from_key(key_bytes)
    except Exception as exc:
        raise ExecutionRefused(
            f"agent wallet custody failed ({type(exc).__name__})"
        ) from None
    finally:
        del key_bytes, passphrase

    recorded = recorded_agent_address()
    if account.address.lower() != recorded.lower():
        raise ExecutionRefused(
            "agent wallet identity mismatch: keystore does not match the "
            "recorded agent address — refusing to sign"
        )
    return account


# ── Chain identity verification ──────────────────────────────────────────────

def check_chain_identity(w3, expected_chain_id: int) -> int:
    """Verify the RPC-REPORTED chain ID equals the executor's expected
    chain, and return the reported value.

    CHAIN_ID is the configured network identity of the running process;
    this check makes the live RPC agree with it at the signing boundary.
    An RPC failure is reduced to a sanitized message (provider URLs can
    carry credentials); a mismatch is a policy refusal kept verbatim.
    """
    try:
        reported = int(w3.eth.chain_id)
    except Exception as exc:
        raise ExecutionRefused(
            "chain identity could not be verified: "
            f"{sanitize_error(exc)}"
        ) from None
    if reported != int(expected_chain_id):
        raise ExecutionRefused(
            f"RPC chain mismatch: expected {int(expected_chain_id)}, "
            f"RPC reports {reported}"
        )
    return reported


# ── Signing ──────────────────────────────────────────────────────────────────

def sign_transaction(w3, tx: dict, *, chain_id: int) -> bytes:
    """Sign one builder-produced transaction — the ONLY signing path.

    Args:
        w3:        Web3 instance used for chain-ID verification.
        tx:        Unsigned transaction dict from builder.build_execute_tx()
                   / build_execute_batch_tx() (already policy-validated).
        chain_id:  The executor's expected chain (config.CHAIN_ID for the
                   running process).

    Returns:
        Raw signed transaction bytes ready for relay submission.

    Raises:
        ExecutionRefused: master switch disabled, chain-identity mismatch
            (expected vs tx field vs RPC-reported), wallet-custody failure
            or a signing failure. Refusals never carry secret material.
    """
    # 1. Master execution switch — the authoritative process read, at the
    #    signing boundary. A disabled run cannot sign. No parameter can
    #    override this.
    if not execution_enabled():
        raise ExecutionRefused(
            "execution is disabled (EXECUTE_ONCHAIN) — refusing to sign"
        )

    # 2. Unsigned transaction chainId must match the expected chain.
    tx_chain = tx.get("chainId")
    if tx_chain is None:
        raise ExecutionRefused(
            "transaction carries no chainId — refusing to sign"
        )
    if int(tx_chain) != int(chain_id):
        raise ExecutionRefused(
            f"transaction chainId {tx_chain} != expected chain "
            f"{int(chain_id)} — refusing to sign"
        )

    # 3. Chain identity: RPC-reported must equal expected (pre-sign).
    check_chain_identity(w3, chain_id)

    # 4. Wallet custody through the single authoritative path.
    account = load_wallet()

    # 5. Re-verify the chain IMMEDIATELY before signing (RPC failover or
    #    a network switch between step 3 and here is refused).
    check_chain_identity(w3, chain_id)

    # 6. Sign. There is no fallback signing implementation. A signing
    #    failure is reduced to its exception class name — eth_account
    #    diagnostics must never carry transaction or key material into a
    #    caller-visible message.
    try:
        signed = account.sign_transaction(dict(tx))
    except ExecutionRefused:
        raise
    except Exception as exc:
        raise ExecutionRefused(
            f"transaction signing failed ({type(exc).__name__})"
        ) from None
    raw = getattr(signed, "raw_transaction", None) or getattr(
        signed, "rawTransaction", None
    )
    return bytes(raw)
