#!/usr/bin/env python3
"""Compile the authoritative Exec contract and produce its ABI artifact.

DSS-WO-ENG-002. Sources: contracts/ as copied byte-for-byte from
Dannyednut/EVM at pinned commit 898fe82f29a5695a01278365eb442ab3a26811b5
(provenance and blob SHAs recorded in contracts/PROVENANCE.md).

Toolchain (pinned):
  - solc 0.8.28+commit.7893614a, installed via py-solc-x from
    binaries.soliditylang.org and SHA-256 verified after download against
    the official checksum published in the solc-bin list.
  - @openzeppelin/contracts@5.7.0 exactly (contracts/package-lock.json).

Run:  python scripts/exec_build.py            # (re)write executor/exec_abi.json
      python scripts/exec_build.py --check    # verify without writing
Exit: 0 = ABI generated and (for --check) equal to the committed artifact,
      1 otherwise. Never deploys, signs or broadcasts anything.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

SOLC_VERSION = "0.8.28+commit.7893614a"
SOLC_VERSION_BASE = "0.8.28"
# Official SHA-256 of the linux-amd64 build published in
# https://binaries.soliditylang.org/linux-amd64/list.json
SOLC_SHA256 = "9a0fb7e0db2c0641dbae1c5cc645dc686820c83af516226abb1c0a2f76636f25"

EVM_PINNED_COMMIT = "898fe82f29a5695a01278365eb442ab3a26811b5"
OUTPUT_PATH = REPO_ROOT / "executor" / "exec_abi.json"

_SOURCES = (
    "contracts/Exec.sol",
    "contracts/libraries/Helper.sol",
    "contracts/interfaces/IUniswapV2Pair.sol",
    "contracts/interfaces/IUniswapV3Pool.sol",
    "contracts/interfaces/IQuoter.sol",
    "contracts/interfaces/IWETH.sol",
    "contracts/interfaces/IBalancerVault.sol",
)


def _verified_solc():
    """Install (if needed) and return the pinned, checksum-verified solc."""
    try:
        import solcx
    except ImportError as e:
        raise RuntimeError(
            "py-solc-x is required to compile Exec.sol; install the dev "
            "requirements (pip install -r requirements-dev.txt)"
        ) from e

    folder = Path(solcx.get_solcx_install_folder())
    # py-solc-x names binaries "solc-v<version>" without the commit suffix;
    # the SHA-256 check below is what pins the exact build identity.
    candidates = sorted(folder.glob(f"solc-v{SOLC_VERSION_BASE}*"))
    if not candidates:
        solcx.install_solc(SOLC_VERSION_BASE)
        candidates = sorted(folder.glob(f"solc-v{SOLC_VERSION_BASE}*"))
    if not candidates:
        raise RuntimeError(f"solc {SOLC_VERSION} not found after install step")
    install_path = candidates[0]
    digest = hashlib.sha256(install_path.read_bytes()).hexdigest()
    if digest != SOLC_SHA256:
        raise RuntimeError(
            f"solc binary checksum mismatch for {SOLC_VERSION}: "
            f"expected {SOLC_SHA256}, got {digest} — refusing to compile"
        )
    return solcx


def _oz_root() -> Path:
    """Locate the npm-installed @openzeppelin/contracts package."""
    oz = REPO_ROOT / "contracts" / "node_modules" / "@openzeppelin" / "contracts"
    if not (oz / "access" / "Ownable.sol").exists():
        raise RuntimeError(
            "@openzeppelin/contracts not found; run `npm ci` inside contracts/ "
            "(see contracts/package-lock.json, pinned @openzeppelin/contracts 5.7.0)"
        )
    return oz


def compile_exec() -> dict:
    """Compile Exec.sol with the pinned toolchain and return the result dict."""
    solcx = _verified_solc()
    oz_root = _oz_root()

    sources = {}
    for rel in _SOURCES:
        p = REPO_ROOT / rel
        sources[rel] = {"content": p.read_text()}

    stdin = {
        "language": "Solidity",
        "sources": sources,
        "settings": {
            "optimizer": {"enabled": True, "runs": 200},
            "remappings": [f"@openzeppelin/contracts/={oz_root.resolve()}/"],
            "outputSelection": {
                "*": {"*": ["abi"]}
            },
        },
    }
    out = solcx.compile_standard(stdin, solc_version=SOLC_VERSION_BASE)
    abi = out["contracts"]["contracts/Exec.sol"]["Exec"]["abi"]
    return {
        "compiler": SOLC_VERSION,
        "solc_sha256": SOLC_SHA256,
        "source_commit": EVM_PINNED_COMMIT,
        "openzeppelin": "5.7.0",
        "abi": abi,
    }


def build_artifact(result: dict) -> dict:
    return {
        "description": (
            "ABI of the authoritative Exec contract, compiler-generated from "
            "the pinned sources recorded in contracts/PROVENANCE.md "
            "(DSS-WO-ENG-002). Generated by scripts/exec_build.py; do not "
            "edit by hand."
        ),
        "source_commit": result["source_commit"],
        "compiler": result["compiler"],
        "solc_sha256": result["solc_sha256"],
        "openzeppelin": result["openzeppelin"],
        "abi": result["abi"],
    }


def main() -> int:
    check = "--check" in sys.argv[1:]
    committed = json.loads(OUTPUT_PATH.read_text()) if OUTPUT_PATH.exists() else None
    artifact = build_artifact(compile_exec())
    if committed is None:
        if check:
            print(f"exec_build: FAIL — {OUTPUT_PATH} does not exist")
            return 1
        OUTPUT_PATH.write_text(json.dumps(artifact, indent=2) + "\n")
        print(f"exec_build: wrote {OUTPUT_PATH} "
              f"({len(artifact['abi'])} ABI entries, solc {artifact['compiler']})")
        return 0
    if committed.get("abi") != artifact["abi"] or committed.get("compiler") != artifact["compiler"]:
        print("exec_build: FAIL — committed executor/exec_abi.json does not "
              "match the ABI generated from the pinned sources")
        return 1
    print(f"exec_build: OK — committed ABI matches solc {artifact['compiler']} output")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
